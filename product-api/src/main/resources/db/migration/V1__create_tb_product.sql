-- product-api: catálogo de produtos (dono = owner_id, usuário do auth-api; sem FK entre bancos)
CREATE TABLE IF NOT EXISTS tb_product (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)     NOT NULL,
    description  TEXT             NOT NULL,
    price        DOUBLE PRECISION NOT NULL,
    category     VARCHAR(255)     NOT NULL,
    sizes        VARCHAR(255),
    colors       VARCHAR(255),
    image        TEXT,
    customizable BOOLEAN          NOT NULL DEFAULT FALSE,
    stock        INTEGER          NOT NULL DEFAULT 0,
    owner_id     BIGINT
);
CREATE INDEX IF NOT EXISTS idx_tb_product_category ON tb_product (category);
CREATE INDEX IF NOT EXISTS idx_tb_product_owner    ON tb_product (owner_id);
