-- order-api: pedidos e itens (user_id/product_id/seller_id referenciam outros serviços, sem FK entre bancos)
CREATE TABLE IF NOT EXISTS tb_order (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total      DOUBLE PRECISION         NOT NULL,
    status     VARCHAR(255)             NOT NULL,
    payment    VARCHAR(255)             NOT NULL,
    zip        VARCHAR(255),
    street     VARCHAR(255),
    number     VARCHAR(255),
    city       VARCHAR(255),
    state      VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS tb_order_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT REFERENCES tb_order (id) ON DELETE CASCADE,
    product_id    BIGINT,
    seller_id     BIGINT,
    product_name  VARCHAR(255),
    unit_price    DOUBLE PRECISION NOT NULL,
    quantity      INTEGER          NOT NULL,
    size          VARCHAR(255),
    color         VARCHAR(255),
    custom_model  VARCHAR(255),
    custom_name   VARCHAR(255),
    custom_number VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_tb_order_user       ON tb_order (user_id);
CREATE INDEX IF NOT EXISTS idx_tb_order_item_order  ON tb_order_item (order_id);
CREATE INDEX IF NOT EXISTS idx_tb_order_item_seller ON tb_order_item (seller_id);
